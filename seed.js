// 분류 + 상품 (기존 DB 마이그레이션에도 사용)
function catalog(now = new Date().toISOString()) {
  const iconOf = id => (CATS.find(c => c.id === id) || {}).icon || '📦';
  return {
    categories: CATS.map((c, i) => ({ id: c.id, name: c.id, top: c.top, order: i + 1, bg: c.bg, icon: c.icon, subs: c.subs })),
    products: P.map(([id, cat0, sub0, name, spec, price, discount, qtys, unit, options, badge, hit, best, soldout], i) => {
      const [cat, sub] = MAP[id] || [cat0, sub0];
      return {
        id, cat, sub, name, spec, discount, unit, options, badge, hit: !!hit, best: !!best, soldout: !!soldout,
        icon: iconOf(cat), img: `/img/products/${id}.svg`,
        desc: `${name} - ${spec}. 치과 로고/상호/연락처를 넣어 맞춤 제작합니다. 파일 업로드 후 시안 확인을 거쳐 제작됩니다.`,
        also: MAP[id] ? [{ cat: cat0, sub: sub0 }] : [],
        tiers: tiers(price, qtys), active: true, views: 0, order: i + 1, createdAt: now,
      };
    }),
  };
}module.exports = { seed, catalog, TOPS, SHOW_ALL };
